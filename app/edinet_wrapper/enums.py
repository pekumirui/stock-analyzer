class DocumentFileType(IntEnum):
    MAIN = 1
    PDF = 2
    ATTACHMENT = 3
    ENGLISH = 4
    CSV = 5

    @property
    def suffix(self) -> str:
        return ".pdf" if self is DocumentFileType.PDF else ".zip"


