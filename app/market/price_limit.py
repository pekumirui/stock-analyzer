"""東証の制限値幅（呼値の基準値段 → 値幅）。

J-Quants の UL / LL が無い過去の日足で、寄らずのストップ高・安かを見るのに使う。
値幅の拡大は考えない（拡大した日も基準の値幅以上動くので判定は変わらない）。
"""
from bisect import bisect_right

# (基準値段の上限（未満）, 制限値幅)
_TABLE = (
    (100, 30), (200, 50), (500, 80), (700, 100), (1_000, 150),
    (1_500, 300), (2_000, 400), (3_000, 500), (5_000, 700), (7_000, 1_000),
    (10_000, 1_500), (15_000, 3_000), (20_000, 4_000), (30_000, 5_000), (50_000, 7_000),
    (70_000, 10_000), (100_000, 15_000), (150_000, 30_000), (200_000, 40_000), (300_000, 50_000),
    (500_000, 70_000), (700_000, 100_000), (1_000_000, 150_000), (1_500_000, 300_000),
    (2_000_000, 400_000), (3_000_000, 500_000), (5_000_000, 700_000), (7_000_000, 1_000_000),
    (10_000_000, 1_500_000), (15_000_000, 3_000_000), (20_000_000, 4_000_000),
    (30_000_000, 5_000_000), (50_000_000, 7_000_000),
)
_BOUNDS = [b for b, _ in _TABLE]


def price_limit(base: float) -> float:
    """基準値段 base の制限値幅（円）。"""
    i = bisect_right(_BOUNDS, base)
    return _TABLE[i][1] if i < len(_TABLE) else 10_000_000


def at_limit(prev_close: float | None, close: float | None) -> bool:
    """前日終値から制限値幅いっぱい動いたか。"""
    if not prev_close or close is None:
        return False
    return abs(close - prev_close) >= price_limit(prev_close) * 0.99
